# Thread-safe guard to prevent re-uploading files that the poller just downloaded.
# Uses a time-based TTL: guarded paths expire after GUARD_TTL_SECONDS so the
# watchdog skips all events (created, modified, etc.) that fire during/after download.
GUARD_TTL_SECONDS = 30
_download_guard: dict[str, float] = {}   # norm_path -> timestamp
_download_guard_lock = threading.Lock()


def _guard_path(file_path: Path):
    """Add a file path to the download guard (call before writing to disk)."""
    norm = str(file_path.resolve()).replace("\\", "/").lower()
    with _download_guard_lock:
        _download_guard[norm] = time.time()


def _check_guard(file_path: Path) -> bool:
    """Check if a file was recently downloaded by the poller.

    Returns True if the file should be skipped (was downloaded within the TTL window).
    Expired entries are cleaned up lazily.
    """
    norm = str(file_path.resolve()).replace("\\", "/").lower()
    now = time.time()
    with _download_guard_lock:
        ts = _download_guard.get(norm)
        if ts is not None:
            if now - ts < GUARD_TTL_SECONDS:
                return True  # still within TTL — skip this file
            # Expired — clean up
            del _download_guard[norm]
    return False


