# Tracks files generated by the poller (meeting note PDFs, nested page PDFs).
# These are "proxy" files that mirror Notion content and must NOT be re-uploaded.
# Stored as .notion_proxies.json in each fund folder.

PROXY_MANIFEST_NAME = ".notion_proxies.json"


def _load_proxy_manifest(folder: Path) -> dict[str, dict]:
    """Load the proxy manifest for a fund folder.

    Returns: {normalized_filename: {"page_id": str, "title": str, "filename": str}}
    """
    manifest_path = folder / PROXY_MANIFEST_NAME
    if not manifest_path.exists():
        return {}
    try:
        return json.loads(manifest_path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _save_proxy_manifest(folder: Path, manifest: dict[str, dict]):
    """Save the proxy manifest for a fund folder."""
    manifest_path = folder / PROXY_MANIFEST_NAME
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )


def _is_proxy_file(file_path: Path) -> bool:
    """Check if a file is a poller-generated proxy (should not be uploaded)."""
    folder = file_path.parent
    manifest = _load_proxy_manifest(folder)
    norm = _normalize_filename(file_path.name)
    return norm in manifest


