def _sanitize_for_pdf(text: str) -> str:
    """Sanitize text for PDF rendering with Helvetica (latin-1 compatible).

    Replaces common Unicode characters with ASCII equivalents and strips
    characters outside the font's supported range.
    """
    # Common substitutions
    replacements = {
        "\u2022": "-",   # bullet •
        "\u2013": "-",   # en dash –
        "\u2014": "--",  # em dash —
        "\u2018": "'",   # left single quote '
        "\u2019": "'",   # right single quote '
        "\u201c": '"',   # left double quote "
        "\u201d": '"',   # right double quote "
        "\u2026": "...", # ellipsis …
        "\u00a0": " ",   # non-breaking space
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    # Strip any remaining non-latin-1 characters (above U+00FF)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _setup_pdf() -> "FPDF":
    """Create an FPDF instance with a Unicode-capable font if available."""
    try:
        from fpdf import FPDF
    except ImportError:
        raise ImportError(
            "fpdf2 is required for PDF export. Install it with: poetry add fpdf2"
        )

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Try to use Arial TTF for better Unicode support
    if os.name == "nt":
        fonts_dir = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts"
    else:
        fonts_dir = Path("/usr/share/fonts/truetype/msttcorefonts")
    arial = fonts_dir / "arial.ttf"
    arial_bold = fonts_dir / "arialbd.ttf"
    arial_italic = fonts_dir / "ariali.ttf"
    arial_bi = fonts_dir / "arialbi.ttf"

    if arial.exists():
        try:
            pdf.add_font("Arial", "", str(arial))
            if arial_bold.exists():
                pdf.add_font("Arial", "B", str(arial_bold))
            if arial_italic.exists():
                pdf.add_font("Arial", "I", str(arial_italic))
            if arial_bi.exists():
                pdf.add_font("Arial", "BI", str(arial_bi))
            pdf._font_family = "Arial"
            log.debug("Using Arial TTF for PDF rendering")
            return pdf
        except Exception:
            log.debug("Failed to load Arial TTF, falling back to Helvetica")

    return pdf


def _pdf_font(pdf) -> str:
    """Return the font family name to use for this PDF instance."""
    # Check if Arial TTF was loaded
    if "arial" in pdf.fonts:
        return "Arial"
    return "Helvetica"


def _pdf_write(pdf, width, height, text: str):
    """Write text to PDF, sanitizing if using a non-Unicode font."""
    font_family = _pdf_font(pdf)
    if font_family == "Helvetica":
        text = _sanitize_for_pdf(text)
    pdf.multi_cell(width, height, text)


def _export_subpage_as_pdf(page_id: str, title: str, dest: Path):
    """
    Export a Notion sub-page as a PDF file.

    Reads all block content from the page and renders it directly to PDF.
    """
    pdf = _setup_pdf()
    font = _pdf_font(pdf)
    pdf.add_page()

    # Title
    pdf.set_font(font, "B", 16)
    _pdf_write(pdf, 0, 10, title)
    pdf.ln(4)

    _render_blocks_to_pdf(pdf, page_id)

    dest.parent.mkdir(parents=True, exist_ok=True)
    # Suppress verbose font subsetting logs from fontTools during PDF output
    fonttools_logger = logging.getLogger("fontTools")
    prev_level = fonttools_logger.level
    fonttools_logger.setLevel(logging.WARNING)
    try:
        pdf.output(str(dest))
    finally:
        fonttools_logger.setLevel(prev_level)
    log.info("Exported sub-page '%s' as PDF -> %s", title, dest.name)


def _render_blocks_to_pdf(pdf, block_id: str, indent: int = 0):
    """Render Notion blocks to a FPDF document."""
    font = _pdf_font(pdf)
    start_cursor = None
    numbered_idx = 0

    while True:
        params = {"page_size": 100}
        if start_cursor:
            params["start_cursor"] = start_cursor
        data = _notion_request(
            "get", f"/blocks/{block_id}/children", params=params
        )
        for block in data.get("results", []):
            btype = block.get("type", "")
            block_data = block.get(btype, {})
            rich_text = block_data.get("rich_text", [])
            text = "".join(t.get("plain_text", "") for t in rich_text)

            left_margin = 10 + indent * 8

            if btype == "heading_1":
                pdf.ln(4)
                pdf.set_font(font, "B", 14)
                pdf.set_x(left_margin)
                _pdf_write(pdf, 0, 7, text)
                pdf.ln(2)
                numbered_idx = 0
            elif btype == "heading_2":
                pdf.ln(3)
                pdf.set_font(font, "B", 12)
                pdf.set_x(left_margin)
                _pdf_write(pdf, 0, 6, text)
                pdf.ln(1)
                numbered_idx = 0
            elif btype == "heading_3":
                pdf.ln(2)
                pdf.set_font(font, "BI", 11)
                pdf.set_x(left_margin)
                _pdf_write(pdf, 0, 6, text)
                numbered_idx = 0
            elif btype in ("paragraph", "quote"):
                pdf.set_font(font, "", 10)
                pdf.set_x(left_margin)
                if text:
                    _pdf_write(pdf, 0, 5, text)
                else:
                    pdf.ln(3)
                numbered_idx = 0
            elif btype == "bulleted_list_item":
                pdf.set_font(font, "", 10)
                pdf.set_x(left_margin + 4)
                _pdf_write(pdf, 0, 5, f"-  {text}")
                numbered_idx = 0
            elif btype == "numbered_list_item":
                numbered_idx += 1
                pdf.set_font(font, "", 10)
                pdf.set_x(left_margin + 4)
                _pdf_write(pdf, 0, 5, f"{numbered_idx}.  {text}")
            elif btype == "to_do":
                checked = block_data.get("checked", False)
                mark = "[x]" if checked else "[ ]"
                pdf.set_font(font, "", 10)
                pdf.set_x(left_margin + 4)
                _pdf_write(pdf, 0, 5, f"{mark}  {text}")
                numbered_idx = 0
            elif btype == "callout":
                pdf.set_font(font, "I", 10)
                pdf.set_x(left_margin + 4)
                if text:
                    _pdf_write(pdf, 0, 5, f"| {text}")
                numbered_idx = 0
            elif btype == "divider":
                y = pdf.get_y()
                pdf.line(left_margin, y, 200, y)
                pdf.ln(3)
                numbered_idx = 0
            elif btype == "table":
                pdf.set_font(font, "", 9)
                table_data = _notion_request(
                    "get", f"/blocks/{block['id']}/children",
                    params={"page_size": 100},
                )
                for row in table_data.get("results", []):
                    cells = row.get("table_row", {}).get("cells", [])
                    cell_texts = [
                        "".join(t.get("plain_text", "") for t in cell)
                        for cell in cells
                    ]
                    pdf.set_x(left_margin)
                    _pdf_write(pdf, 0, 5, " | ".join(cell_texts))
                pdf.ln(2)
                numbered_idx = 0
            else:
                # Unknown block type with text
                if text:
                    pdf.set_font(font, "", 10)
                    pdf.set_x(left_margin)
                    _pdf_write(pdf, 0, 5, text)
                numbered_idx = 0

            # Recurse into children (except tables, handled above)
            if block.get("has_children") and btype not in ("table",):
                _render_blocks_to_pdf(pdf, block["id"], indent + 1)

        if not data.get("has_more"):
            break
        start_cursor = data.get("next_cursor")


def _collect_file_urls_from_block(block_id: str, recurse_into: set[str] | None = None) -> list[dict]:
    """
    Collect downloadable file URLs and sub-page references from a block's children.

    Args:
        block_id: Parent block (page or callout) to scan
        recurse_into: Block types to recurse into (e.g. {"callout"})

    Returns:
        List of dicts, each either:
          - {"name": filename, "url": download_url}              (file)
          - {"name": "Title.pdf", "page_id": id, "title": title} (sub-page)
    """
    if recurse_into is None:
        recurse_into = {"callout"}

    file_block_types = {"file", "pdf", "image", "audio", "video"}
    files = []
    start_cursor = None

    while True:
        params = {"page_size": 100}
        if start_cursor:
            params["start_cursor"] = start_cursor
        data = _notion_request(
            "get", f"/blocks/{block_id}/children", params=params
        )
        for block in data.get("results", []):
            btype = block.get("type", "")

            # Sub-pages → export as PDF
            if btype == "child_page":
                title = block.get("child_page", {}).get("title", "")
                if title:
                    files.append({
                        "name": f"{title}.pdf",
                        "page_id": block["id"],
                        "title": title,
                    })
                continue

            # Recurse into callouts (Data Packs sections)
            if btype in recurse_into and block.get("has_children"):
                files.extend(
                    _collect_file_urls_from_block(block["id"], recurse_into)
                )
                continue

            if btype not in file_block_types:
                continue

            block_data = block.get(btype, {})

            # Notion file blocks have an inner type: "file" (hosted)
            # or "file_upload" (user-uploaded). Extract URL from either.
            inner_type = block_data.get("type", "")
            if inner_type == "file":
                url = block_data.get("file", {}).get("url")
            elif inner_type == "file_upload":
                url = block_data.get("file_upload", {}).get("url")
            else:
                # Fallback: try both
                url = (block_data.get("file", {}).get("url")
                       or block_data.get("file_upload", {}).get("url"))
            if not url:
                continue

            name = block_data.get("name")
            if not name:
                name = _extract_filename_from_url(url)
            if not name:
                continue

            files.append({"name": name, "url": url})

        if not data.get("has_more"):
            break
        start_cursor = data.get("next_cursor")

    return files


def _download_file(url: str, dest: Path):
    """Download a file from a URL to a local path."""
    resp = requests.get(url, stream=True, timeout=120)
    resp.raise_for_status()
    dest.parent.mkdir(parents=True, exist_ok=True)
    with open(dest, "wb") as f:
        for chunk in resp.iter_content(chunk_size=8192):
            f.write(chunk)
    log.info("Downloaded '%s'", dest.name)


def _get_meeting_notes_items(page_id: str) -> list[dict]:
    """
    Fetch pages linked via the 'Meeting Notes' relation property on a fund page.

    Returns a list of dicts: {"name": "Title.pdf", "page_id": id, "title": title}
    """
    items = []
    try:
        page_data = _notion_request("get", f"/pages/{page_id}")
    except Exception as e:
        log.error("Failed to fetch page %s for Meeting Notes: %s", page_id, e)
        return items

    relations = (
        page_data.get("properties", {})
        .get("Meeting Notes", {})
        .get("relation", [])
    )
    for rel in relations:
        try:
            meeting_page = _notion_request("get", f"/pages/{rel['id']}")
        except Exception as e:
            log.error("Failed to fetch meeting note page %s: %s", rel["id"], e)
            continue

        # Extract title from the meeting notes page (try common title property names)
        props = meeting_page.get("properties", {})
        title = ""
        for prop_name, prop_val in props.items():
            if prop_val.get("type") == "title":
                title_parts = prop_val.get("title", [])
                title = "".join(t.get("plain_text", "") for t in title_parts)
                break

        if title:
            items.append({
                "name": f"{title}.pdf",
                "page_id": rel["id"],
                "title": title,
            })
        else:
            log.warning("Meeting note page %s has no title, skipping", rel["id"])

    return items


def _sync_files_from_notion_page(page_id: str, local_folder: Path):
    """
    Download files and export sub-pages from a Notion fund page to the local folder.

    Maintains a proxy manifest to track Notion-origin files:
      - Files uploaded directly to Notion (not from the folder)
      - Meeting note PDFs exported from relation properties
      - Nested page PDFs exported from child_page blocks

    Origin rules:
      - Notion-origin: file was first seen on Notion and downloaded by the poller.
        Tracked in the manifest. Deleted locally when removed from Notion.
      - Folder-origin: file existed locally before the poller downloaded it (i.e.
        it was uploaded to Notion from the folder). NOT tracked in the manifest.
        Never auto-deleted locally, even if removed from Notion.
    """
    if not local_folder.exists():
        log.warning("Local folder does not exist, skipping download: %s", local_folder)
        return

    # Collect remote items: file blocks, child pages, and Meeting Notes relations
    remote_items = _collect_file_urls_from_block(page_id)
    meeting_items = _get_meeting_notes_items(page_id)
    remote_items.extend(meeting_items)

    # Build a lookup of ALL remote items by normalized name
    remote_names: dict[str, dict] = {}
    for item in remote_items:
        norm = _normalize_filename(item["name"])
        if "page_id" in item:
            remote_names[norm] = {
                "page_id": item["page_id"],
                "title": item["title"],
                "filename": item["name"],
            }
        else:
            remote_names[norm] = {
                "filename": item["name"],
            }

    # Load existing manifest and reconcile
    manifest = _load_proxy_manifest(local_folder)

    # --- Delete stale proxies (in manifest but no longer on Notion) ---
    stale_keys = set(manifest.keys()) - set(remote_names.keys())
    for norm_name in stale_keys:
        entry = manifest[norm_name]
        local_file = local_folder / entry["filename"]
        if local_file.exists():
            # Guard the path so watchdog on_deleted doesn't propagate to Notion
            _guard_path(local_file)
            local_file.unlink()
            log.info(
                "Deleted stale proxy '%s' (removed from Notion)",
                entry["filename"],
            )
        del manifest[norm_name]

    # --- Download new items (only those not already local) ---
    # Files that already exist locally are folder-origin and are NOT added
    # to the manifest, so they will never be auto-deleted.
    existing_local = {
        _normalize_filename(f.name)
        for f in local_folder.iterdir()
        if f.is_file() and f.name != PROXY_MANIFEST_NAME
    }

    for item in remote_items:
        norm = _normalize_filename(item["name"])
        if norm in existing_local:
            continue

        dest = local_folder / item["name"]

        # Guard the path before writing so the watchdog skips it
        _guard_path(dest)

        if "page_id" in item:
            # Sub-page or meeting note → export as PDF
            try:
                _export_subpage_as_pdf(item["page_id"], item["title"], dest)
                manifest[norm] = {
                    "page_id": item["page_id"],
                    "title": item["title"],
                    "filename": item["name"],
                }
            except Exception as e:
                log.error("Failed to export sub-page '%s': %s", item["title"], e)
        else:
            # Regular file uploaded directly to Notion → download and track
            try:
                _download_file(item["url"], dest)
                manifest[norm] = {
                    "filename": item["name"],
                }
            except Exception as e:
                log.error("Failed to download '%s': %s", item["name"], e)

    # Update manifest entries with current remote state
    # (ensures any page_id changes or title renames are captured)
    for norm, info in remote_names.items():
        if norm in manifest:
            manifest[norm] = info

    _save_proxy_manifest(local_folder, manifest)


def _get_fund_page_info(page: dict) -> tuple[str, str, str]:
    """
    Extract fund name, identifier, and firm name from a fund page dict.

    Returns:
        (fund_name, identifier, firm_page_id)
    """
    props = page.get("properties", {})

    # Fund name
    title_parts = props.get(FUND_TITLE_PROP, {}).get("title", [])
    fund_name = "".join(t.get("plain_text", "") for t in title_parts)

    # Identifier
    id_parts = props.get("Identifier", {}).get("rich_text", [])
    identifier = "".join(t.get("plain_text", "") for t in id_parts)

    # AM Firm relation
    relation = props.get("AM Firm", {}).get("relation", [])
    firm_page_id = relation[0]["id"] if relation else ""

    return fund_name, identifier, firm_page_id


def _resolve_local_fund_folder(
    watch_folder: Path, firm_page_id: str, firm_db_id: str,
    fund_name: str,
) -> Path | None:
    """
    Find the local folder path for a fund page.

    Only returns a path if a matching folder already exists on disk.
    Returns None if no corresponding local folder is found (no download
    should happen for fund pages without a local folder).
    """
    # Get firm name from Notion
    if not firm_page_id:
        return None
    try:
        firm_data = _notion_request("get", f"/pages/{firm_page_id}")
    except Exception:
        return None

    firm_props = firm_data.get("properties", {})
    firm_title_parts = firm_props.get(FIRM_TITLE_PROP, {}).get("title", [])
    firm_name = "".join(t.get("plain_text", "") for t in firm_title_parts)
    if not firm_name:
        return None

    firm_folder = watch_folder / firm_name
    if not firm_folder.exists():
        return None

    # Try to find existing fund folder (with or without identifier)
    for sub in firm_folder.iterdir():
        if not sub.is_dir():
            continue
        parsed = parse_fund_folder_name(sub.name)
        if parsed and parsed[0] == fund_name:
            return sub
        if sub.name == fund_name:
            return sub

    # No matching folder found — do not create one
    return None


